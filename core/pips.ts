// 牌面美术：花色符号与点位。全部代码画（项目不许用任何外部素材），
// 走内联 SVG 而不是系统里的 ♠♥♦♣ 字符——那四个字符是字体给的，换机器就换形，
// 而且线条是"印刷体"的，跟这间牌局的铜版画味不搭。
//
// 三条规矩：
// 1. **点位按真实扑克牌排**（2..10 各有固定位置，下半部的点旋转 180°）。
//    原来所有数字牌都在正中放一个 40px 的大符号，于是 9 和 2 只差角标数字——
//    第一次玩的人扫一眼手牌读不出"哪张点多"。
// 2. 坐标一律用**归一化 0..1**，由 CSS 的 inset/百分比落位。写死像素的话，
//    窄屏那套 --card-w: 78px 会让点位溢出牌面。
// 3. 这是**呈现**不是算术：牌面画几个点，跟这张牌值几分毫无关系（分数在 hands.ts）。
//    所以这里不 import 任何计分东西，自检也只查形状不查数值。

