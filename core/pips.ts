export interface Pip { x: number; y: number; flip: boolean }

/** 某一rank 的点位（含"要不要倒过来"）。A 与人头牌不走这里 */
export const pipSpots = (rank: number): Pip[] =>
  (PIP_SPOTS[rank] ?? []).map(([x, y]) => ({ x, y, flip: y > 0.5 }));

/** 这张牌走不走"点位排布"：2..10 走，A 与 J/Q/K 走中心大图形 */
export const isPipCard = (rank: number): boolean => rank >= 2 && rank <= 10;

