import assert from 'node:assert/strict';
import { exampleCards } from '../web/reference.ts';
import { runReview } from '../web/run-review.ts';
import { HANDS, evaluate } from '../core/hands.ts';
import { Game, targetOf } from '../core/game.ts';
let checks = 0;
const check = (message, fn) => { fn(); checks++; console.log(`ok ${message}`); };
for (const kind of Object.keys(HANDS)) check(`${HANDS[kind].name}示例被真实内核识别`, () => assert.equal(evaluate(exampleCards(kind)).kind, kind));
const g = new Game(4242), s = g.state;
s.score = 270; s.handsLeft = 0; s.discardsLeft = 2; s.status = 'lost';
s.consumables = [{t:'letter',id:'lens'}, {t:'book',id:'pair'}];
s.ledger.push({night:1,stage:'small',label:'便宴',target:100,best:150,reward:1,profit:0,money:10,raised:0,rep:0});
const before = JSON.stringify(s), calls = g.rand.calls;
const r = runReview(s, false);
check('失败差额采用内核彩头', () => assert.equal(r.gap, targetOf(s) - s.score));
check('当前失败场参与最高流水', () => assert.equal(r.best, 270));
check('复盘命名真实随身物品', () => assert.ok(r.resources.includes('磨镜、对子谱')));
check('剩余弃牌提示来自实况', () => assert.ok(r.tips.some((t) => t.includes('2 次弃牌'))));
check('查阅复盘不消耗随机数或修改局面', () => { assert.equal(JSON.stringify(s), before); assert.equal(g.rand.calls, calls); });
s.ledger[0].best = 350; s.score = 0;
check('胜局复盘读取最终已结清账本', () => { const w = runReview(s, true); assert.equal(w.target, 100); assert.equal(w.score, 350); assert.equal(w.gap, 0); });
s.discardsLeft = 0; s.consumables = [];
check('没有剩余资源时不编造弃牌和物品建议', () => { const t = runReview(s, false).tips.join(''); assert.ok(!t.includes('次弃牌') && !t.includes('随身物品')); });
console.log(`REFERENCE CHECK OK ${checks} 项`);
